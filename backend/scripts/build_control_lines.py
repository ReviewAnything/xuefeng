def build():
    by_year = {}
    coverage = set()
    for year in sorted(RAW):
        batch = {}
        for province, rows in RAW[year].items():
            coverage.add(province)
            prov = {}
            for subj_token, tier_token, score in rows:
                tier, line = TIER_MAP[tier_token]
                for subject in SUBJ_MAP[subj_token]:
                    if tier in prov.get(subject, {}):
                        raise ValueError(f"{year} {province} {subject} {tier} 重复定义")
                    prov.setdefault(subject, {})[tier] = {"line": line, "score": score}
            batch[province] = prov
        by_year[str(year)] = {"batch_lines": batch}

    meta = {
        "source": "official_chsi_control_lines",
        "source_name": "阳光高考（教育部高校招生阳光工程指定平台）",
        "years": sorted(int(y) for y in RAW),
        "coverage": sorted(coverage),
        "coverage_count": len(coverage),
        "rank_included": False,
        "rank_note": "省控线主表不含一分一段位次；位次须由各省一分一段表另取，本数据集不收录，min_rank 留空。",
        "normalized_note": "科类归一为 物理类/历史类（理工→物理类，文史→历史类，综合不分科双写）；"
                          "档位归一为 普通一本(特控线/本科一批)、普通二本(本科批/一段/本科二批)、专科(专科批/二段/高职)。"
                          "西藏取 A 类（汉族/普通班）值；主表未列出的线不臆造，故部分省份部分档位缺失属正常。",
        "sources": SOURCES,
        "note": "2022–2026 五年全国 31 省官方高考录取控制分数线（省控线/批次线）。"
                "数据来自阳光高考逐年主表，为各省教育考试院官方发布口径；"
                "历史列/物理列按官方主表两列分列转录（2026-10-21 修正过一次两列混写的系统性错误）。",
    }
    return {"meta": meta, "by_year": by_year}


def main():
    data = build()
    out = os.path.join(os.path.dirname(__file__), "..", "data", "admission_control_lines_2022_2026.json")
    out = os.path.abspath(out)
    with open(out, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    # 统计
    total = 0
    for y, blk in data["by_year"].items():
        n = sum(len(s) for p in blk["batch_lines"].values() for s in p.values())
        total += n
        provinces = len(blk["batch_lines"])
        print(f"  {y}: {provinces} 省, {n} (省×科类×档位) 行")
    print(f"已写出 {out}")
    print(f"覆盖 {data['meta']['coverage_count']} 省, 共 {total} 行")


if __name__ == "__main__":
    main()
